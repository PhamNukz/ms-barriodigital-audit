-- audit.timeline (Prueba 3): registro de acciones, quien / que / cuando / desde donde.
-- Tabla aparte de evento_auditoria, que ya guarda el mismo cambio visto desde requests.events.
CREATE TABLE accion_auditoria (
    id              NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR2(60)   NOT NULL UNIQUE,
    event_timestamp TIMESTAMP      NOT NULL,
    actor           VARCHAR2(150)  NOT NULL,
    accion          VARCHAR2(30)   NOT NULL,
    tramite_id      NUMBER(19),
    vecino_username VARCHAR2(150),
    detalle         VARCHAR2(200),
    nota            VARCHAR2(500),
    origen          VARCHAR2(100)
);
